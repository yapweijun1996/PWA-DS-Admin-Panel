import { readFile, writeFile, readdir, mkdir } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

export async function discoverAssets(root) {
  const assets = [];
  async function walk(directory) {
    for (const entry of await readdir(new URL(directory, root), { withFileTypes: true })) {
      const path = `${directory}${entry.name}`;
      if (entry.isDirectory()) await walk(`${path}/`);
      else if (/\.(?:css|js|json|png|svg|webmanifest)$/i.test(entry.name)) assets.push(`./${path}`);
    }
  }
  for (const directory of ['css/', 'js/', 'components/', 'tokens/', 'icons/']) await walk(directory);
  for (const entry of await readdir(root, { withFileTypes: true })) {
    if (entry.isFile() && (/\.html$/i.test(entry.name) || ['version.json', 'manifest.webmanifest'].includes(entry.name))) assets.push(`./${entry.name}`);
  }
  return assets.sort();
}

export async function stampBuild(root = new URL('../', import.meta.url), build = new Date().toISOString().replace(/[^\d]/g, '')) {
  const { version } = JSON.parse(await readFile(new URL('version.json', root), 'utf8'));
  if (typeof version !== 'string' || !version.trim()) throw new Error('version.json must contain a non-empty version string.');
  await mkdir(new URL('js/', root), { recursive: true });
  await writeFile(new URL('js/build-info.js', root), `// Generated by scripts/stamp-build.mjs.\nexport const VERSION = ${JSON.stringify(version)};\nexport const BUILD = ${JSON.stringify(build)};\n`);
  const assets = await discoverAssets(root);
  const workerURL = new URL('sw.js', root);
  const source = await readFile(workerURL, 'utf8');
  if (!/^const BUILD = .*;$/m.test(source) || !/^const PRECACHE = .*;$/m.test(source)) throw new Error('Service worker build markers are missing.');
  const stamped = source.replace(/^const BUILD = .*;$/m, `const BUILD = '${build}';`).replace(/^const PRECACHE = .*;$/m, `const PRECACHE = ${JSON.stringify(assets)};`);
  await writeFile(workerURL, stamped);
  return { version, build, assets };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await stampBuild();
